// loudness.h
// Перевод амплитуды сэмплов (int16, наш формат PCM после >>16 из I2S) в дБ
// относительно полной шкалы (dBFS — decibels relative to full scale).
//
// ВАЖНО: это ОТНОСИТЕЛЬНАЯ величина (0 дБ = максимум, который вообще может
// представить 16-битный сэмпл, дальше только отрицательные значения), а НЕ
// калиброванный уровень звукового давления (дБ SPL) в духе шумомера. Для
// настоящего дБ SPL нужна калибровка микрофона по эталонному источнику
// звука известной громкости — у нас её нет, и у дешёвого MEMS-микрофона без
// заводской калибровки чувствительности такая цифра всё равно была бы
// весьма условной. dBFS зато честно показывает: (а) относительную громкость
// разных событий друг к другу и (б) насколько близко событие было к
// клиппингу капсюля. Экран и CSV подписывают это как "дБ" — трактовать как
// "громче/тише", не как паспортную величину.
#pragma once

namespace Loudness {

// amplitude — пиковая или RMS-амплитуда сэмплов, 0..32768. Возвращает дБFS
// (<= 0, в тишине не уходит ниже "пола" примерно -90 дБ — просто чтобы не
// получить -inf).
float toDbfs(float amplitude);

} // namespace Loudness
