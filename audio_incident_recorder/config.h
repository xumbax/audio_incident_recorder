// config.h
// Регистратор аудио-инцидентов (сирены/хлопки) — общая конфигурация.
//
// ЖЕЛЕЗО (по факту заказанного, см. проект narodmon / audio-incident-recorder-design.md):
//   MCU:    ESP32-S3 N16R8 (16MB flash, 8MB Octal PSRAM) — дженерик dev-плата
//   Дисплей: SPI TFT 240x320, ILI9341
//   Микрофон: INMP441 (I2S MEMS, только приём)
//   SD:      microSD модуль со своим стабилизатором, SPI (общая шина с TFT, свой CS)
//
// ВАЖНО ПРО ПИНЫ: ниже — пины для "обычного" дженерик ESP32-S3-WROOM-1 N16R8 dev-kit
// (аналог официального DevKitC-1). На платах с Octal PSRAM (R8) GPIO33-37 заняты
// внутренней шиной к PSRAM/flash и НЕ должны использоваться — ниже они не используются.
// Проверьте распиновку конкретно вашей платы по шелкографии перед пайкой — готовые платы
// разных производителей иногда отличаются (см. историю с ESP32-2432S028 в заметках проекта).
//
// Примечание по стилю: все константы ниже — через #define, а не static const.
// Так каждая единица трансляции (.cpp), которая просто подключает config.h,
// но не использует какую-то конкретную константу, не получает предупреждение
// компилятора "defined but not used" (а у нас в проекте это предупреждение
// превращено в ошибку сборки платформой esp32 при --warnings all).

#pragma once
#include <Arduino.h>

// ---------------------------------------------------------------------------
// I2S микрофоны (2x INMP441 — ВЕРТИКАЛЬНАЯ пара для оценки угла места
// "снизу/сверху", см. direction.h). ОБА микрофона сидят на ОДНОЙ и той же
// шине — BCLK/WS/DIN общие, новых GPIO не нужно. Единственное отличие между
// ними — пин L/R (WS SEL): у нижнего (у самого устройства) микрофона впаян
// на GND ("L"-канал), у верхнего (на мачте, выше на MIC_SPACING_M) — на VDD
// ("R"-канал). Каждый выдаёт данные только в свой тайм-слот I2S-кадра,
// поэтому конфликта на общей линии данных нет — это стандартный приём
// получения синхронной стерео-пары из двух дешёвых I2S MEMS микрофонов.
// Кабель от микрофонов — экранированный, каждая сигнальная жила в своей паре
// с GND, экран заземлить только на стороне платы. Разная длина кабеля до
// нижнего и верхнего микрофона (второй дальше по мачте) НЕ портит измерение —
// I2S тактируется синхронно (~1 МГц), разница хода сигнала по проводу на
// метр-другой — единицы наносекунд, на много порядков меньше, чем разрешение
// по времени, которое вообще участвует в расчёте (десятки микросекунд).
// Общая рекомендация — не давать проводам провисать/хлопать на ветру и
// держать общую длину до дальнего (верхнего) микрофона в разумных пределах
// (несколько метров, экранированный кабель).
// ФИЗИЧЕСКАЯ УСТАНОВКА: микрофон на GND ("L") — НИЖНИЙ, у самого устройства;
// микрофон на VDD ("R") — ВЕРХНИЙ, выше по мачте на MIC_SPACING_M. Если после
// монтажа "снизу/сверху" на экране/в логе окажутся перепутаны местами — не
// перепаивайте, просто поставьте MIC_SWAP_CHANNELS 1 ниже.
// ---------------------------------------------------------------------------
#define PIN_I2S_BCLK   4   // SCK микрофонов (общий)
#define PIN_I2S_WS     5   // WS / LRCLK микрофонов (общий)
#define PIN_I2S_DIN    6   // SD (данные) микрофонов -> вход ESP32 (общий)

// ---------------------------------------------------------------------------
// TFT ILI9341 240x320 по SPI. Реальные пины дублируются в TFT_eSPI/User_Setup.h —
// оба места должны совпадать, см. README.md.
// ---------------------------------------------------------------------------
#define PIN_TFT_SCLK   12
#define PIN_TFT_MOSI   11
#define PIN_TFT_MISO   13
#define PIN_TFT_CS     10
#define PIN_TFT_DC      9
#define PIN_TFT_RST     8
#define PIN_TFT_BL     14  // подсветка (просто HIGH)

// ---------------------------------------------------------------------------
// microSD — сидит на той же физической SPI-шине, что и TFT (SCLK/MOSI/MISO общие),
// свой CS.
// ---------------------------------------------------------------------------
#define PIN_SD_CS      21

// ---------------------------------------------------------------------------
// Аудио: частота дискретизации и размер кадра анализа
// ---------------------------------------------------------------------------
#define SAMPLE_RATE_HZ   16000
#define FRAME_SAMPLES    320                                   // 20 мс на кадр при 16 кГц
#define FRAME_MS         (1000.0f * FRAME_SAMPLES / SAMPLE_RATE_HZ)

// Кольцевой пре-ролл буфер (в PSRAM) — сколько держим "истории" ДО срабатывания
// порога, чтобы не потерять начало быстрого фронта (актуально для хлопков).
#define PREROLL_SEC        0.5f
#define PREROLL_SAMPLES    ((size_t)(PREROLL_SEC * SAMPLE_RATE_HZ))

// Буфер захвата одного события (в PSRAM). Хватает с запасом на любой "хлопок"
// и на представительный фрагмент начала сирены (дальше сирена трекается только
// по огибающей/паттерну, без хранения сырого звука целиком — см. event_detector).
#define CAPTURE_MAX_SEC       6.0f
#define CAPTURE_MAX_SAMPLES   ((size_t)(CAPTURE_MAX_SEC * SAMPLE_RATE_HZ))

// ---------------------------------------------------------------------------
// Детектор событий: пороги громкости (все — TUNE ME, см. README про калибровку
// по факту на месте установки)
// ---------------------------------------------------------------------------
#define NOISE_FLOOR_EMA_ALPHA   0.0015f  // скорость адаптации фона (медленно)
#define NOISE_FLOOR_MIN         40.0f    // не даём полу уйти в 0 в идеальной тишине
#define THRESH_START_RATIO      5.0f     // старт события: RMS > пол*ratio
#define THRESH_END_RATIO        2.5f     // конец: RMS < пол*ratio (гистерезис)
#define START_FRAMES_NEEDED     2        // подряд громких кадров для старта (40мс)
#define END_FRAMES_NEEDED       15       // подряд тихих кадров для конца (300мс)
#define MAX_EVENT_SEC            600.0f  // аварийный потолок длительности события (сирена может длиться минуты)

// Порог классификации "тональность похожа на сирену"
#define TONE_RATIO_THRESHOLD    3.0f     // энергия в полосе / энергия опорных бинов вне полосы
#define TONE_CONFIRM_SEC        1.2f     // столько тон должен держаться, чтобы считать событие сиреной
#define SIREN_BAND_LOW_HZ       500.0f
#define SIREN_BAND_HIGH_HZ      1500.0f
#define SIREN_BAND_BINS         12       // число полос Гёрцеля в диапазоне сирены

// Для затянувшейся сирены: пауза между "гудками", после которой считаем всю
// серию завершённой (а не отдельным новым событием)
#define SIREN_SEQUENCE_GAP_SEC  3.0f

// Максимум отрезков тона в одной серии сирены, которые храним для описания
// паттерна (дальше просто перестаём добавлять новые, длительность серии
// продолжает считаться)
#define MAX_SIREN_SEGMENTS      24

// ---------------------------------------------------------------------------
// Угол места звука (снизу/сверху) по ВЕРТИКАЛЬНОЙ паре микрофонов — см.
// direction.h/.cpp. Изначально (08.09.2026) второй INMP441 ставился
// ГОРИЗОНТАЛЬНО для оценки лево/право; по итогам разбора (25.09.2026, см.
// audio-incident-recorder-design.md в проекте narodmon) решили, что для
// задачи "гроза в небе / бахнуло рядом на земле / бахнуло вдали и высоко"
// полезнее вертикальный монтаж (нижний микрофон у устройства, верхний — на
// мачте выше) — лево/право при этом теряется, остаётся только ось
// низ/верх. Это НЕ дальномер (см. direction.h) — угол места зависит от
// отношения высоты источника к дальности до него, а не от дальности отдельно.
// ---------------------------------------------------------------------------
#define MIC_SWAP_CHANNELS   0  // если "снизу/сверху" на экране окажутся
                               // перепутаны местами после монтажа — поставить
                               // 1 (см. выше), перепайка не нужна

#define MIC_SPACING_M         1.00f  // TUNE ME: реальное расстояние между
                                      // нижним и верхним микрофоном по вертикали,
                                      // метры — подставить точно измеренное после
                                      // монтажа на мачте. Дефолт 1.00м подобран под
                                      // разбор в заметках проекта: даёт разумный
                                      // запас для "бахнуло в 1км на высоте
                                      // 100-200м" и не требует длинной/тяжёлой
                                      // консоли на мачте. Больше база — точнее
                                      // оценка (особенно для далёких/невысоких
                                      // источников), но у величины ~1.5-2м и выше
                                      // практический потолок: длиннее и тяжелее
                                      // мачта (парусность/вибрации от ветра), и на
                                      // открытом воздухе широко разнесённые
                                      // микрофоны хуже коррелируют между собой
                                      // (разная турбулентность/отражения на каждый) —
                                      // это не считается формулой, но на практике
                                      // может смазывать пик корреляции сильнее, чем
                                      // растёт теоретическое разрешение.
#define SPEED_OF_SOUND_MPS    343.0f // скорость звука в воздухе, м/с (~20°C)

#define DIRECTION_WINDOW_SEC        0.3f  // окно вокруг фронта события для кросс-корреляции нижнего/верхнего каналов
#define DIRECTION_WINDOW_SAMPLES    ((size_t)(DIRECTION_WINDOW_SEC * SAMPLE_RATE_HZ))
#define DIRECTION_CENTER_DEADBAND_FRAC  0.20f // доля от теоретического максимума
                                               // задержки (MIC_SPACING_M/скорость
                                               // звука), внутри которой считаем
                                               // высоту источника "по центру"
                                               // (примерно на уровне линии микрофонов)

