// watchdog_diag.h
// Task watchdog + периодический heap-лог — по мотивам диагностики,
// наработанной на weather_display (см. заметки проекта:
// логирование heap/фрагментации раз в несколько минут очень помогает при
// разборе зависаний).
#pragma once

namespace WatchdogDiag {

void begin();

// Покормить вотчдог — звать из каждой долгоживущей задачи (event_detector,
// main loop) не реже, чем раз в WDT_TIMEOUT_SEC.
void feed();

// Раз в HEAP_LOG_INTERVAL_MS печатает в Serial и (если доступна) в SD
// /diag.log: свободный heap, крупнейший свободный блок (фрагментация),
// аптайм, статус Wi-Fi. Вызывать из loop().
void poll();

// Защита от бесконечного цикла перезагрузок. Если несколько последних
// загрузок ПОДРЯД заканчивались паникой/сторожевым таймером (а не обычным
// стартом от кнопки/питания), возвращает true — .ino в этом случае
// пропускает инициализацию экрана (см. DisplayUI::setEnabled()) и работает
// дальше без него: устройство хотя бы продолжает слушать и писать на SD
// вместо того чтобы бесконечно и молча падать в цикле. Решение принимается
// один раз за загрузку (при первом вызове) и дальше кэшируется. Счётчик
// живёт в RTC-памяти — переживает программный резет/панику, обнуляется при
// полном отключении питания.
bool shouldSkipRiskyInit();

// Звать один раз из loop(), когда с момента старта прошло достаточно
// времени, чтобы считать этот запуск успешным (см. STABLE_UPTIME_MS в
// .ino) — сбрасывает счётчик серии падений, чтобы следующая случайная
// перезагрузка не сразу включала безопасный режим.
void markBootStable();

} // namespace WatchdogDiag
