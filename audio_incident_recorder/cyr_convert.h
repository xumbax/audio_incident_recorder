// cyr_convert.h
// Русские строковые литералы в исходниках компилятор кладёт как UTF-8, а
// самодельный шрифт cyr_font.h (см. tools/gen_cyr_font.py) — однобайтовый,
// в раскладке, совпадающей с CP1251 для кириллического диапазона. Эта
// функция конвертирует UTF-8 -> тот самый однобайтовый набор перед тем, как
// текст уйдёт в tft.drawString().
#pragma once
#include <stddef.h>

// out должен быть не меньше исходной строки (однобайтовые символы никогда не
// длиннее своего UTF-8 представления). Непокрытые шрифтом символы
// заменяются на '?'. Возвращает число записанных байт (без завершающего 0).
size_t utf8ToCp1251(const char *utf8, char *out, size_t outSize);
