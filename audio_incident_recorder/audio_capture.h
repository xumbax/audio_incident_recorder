// audio_capture.h
// Непрерывный захват с ДВУХ INMP441 по одной I2S-шине в стерео-режиме (нижний
// микрофон, у устройства — L/R пин на GND, верхний, на мачте выше — на VDD,
// общие BCLK/WS/DIN, см. config.h). Отдельная FreeRTOS-задача на ядре 0
// читает I2S и складывает готовые синхронные пары (left,right) int16-сэмплов
// в потоковый буфер, откуда их вычитывает детектор событий (на ядре 1, вместе
// с loop()). Второй канал используется ТОЛЬКО для грубой оценки угла места
// "снизу/сверху" (см. direction.h) — вся остальная детекция по-прежнему
// работает с моно (среднее L/R), см. event_detector.cpp.
#pragma once
#include <Arduino.h>

namespace AudioCapture {

// Инициализация I2S (RX-only, стерео, 16кГц/16бит эффективных из 32-битного
// фрейма на канал) и запуск задачи захвата. Вызывать один раз из setup().
bool begin();

// Забрать до maxPairs синхронных стерео-сэмплов (по одному значению на канал
// на "тик") — блокирующий вызов с таймаутом. Возвращает реальное число
// прочитанных пар (может быть меньше maxPairs, в т.ч. 0 при таймауте).
// ВНИМАНИЕ: maxPairs не должно превышать FRAME_SAMPLES (config.h) — внутри
// используется статический scratch-буфер этого размера; больший запрос будет
// молча обрезан до FRAME_SAMPLES.
size_t readStereoSamples(int16_t *dstLeft, int16_t *dstRight, size_t maxPairs, uint32_t timeoutMs);

// Сколько пар уже накопилось в буфере и ждут чтения (для диагностики — если
// постоянно растёт, детектор не успевает обрабатывать поток).
size_t availableSamples();

// Диагностика: сколько кадров I2S потеряно из-за переполнения потокового
// буфера с момента старта (в норме должно быть 0).
uint32_t droppedFrames();

} // namespace AudioCapture
