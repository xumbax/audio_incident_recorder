// direction.h
// Грубая оценка УГЛА МЕСТА звука — "источник ближе к земле" или "источник
// приподнят/в воздухе" — по паре микрофонов, смонтированных ВЕРТИКАЛЬНО
// (нижний — у самого устройства, верхний — на мачте выше, см. config.h).
// Метод — TDOA (разница времени прихода одного и того же звука в нижний и
// верхний канал), оценивается кросс-корреляцией сырых, НЕ усреднённых
// каналов. Это НЕ дальномер и НЕ компас: пара микрофонов даёт направление
// только вдоль своей оси (линии между микрофонами) — здесь ось вертикальная,
// поэтому измеряется угол места (низко/высоко), а не азимут (по сторонам).
// У метода есть неоднозначность по азимуту: источник на любой стороне света
// под ОДНИМ И ТЕМ ЖЕ углом места даёт одинаковую задержку — метод в принципе
// не может сказать, с какой стороны горизонта пришёл звук, только "насколько
// он приподнят над горизонтом линии микрофонов". Оценка расстояния до
// источника из одного этого угла невозможна без дополнительных допущений и
// на реальных дистанциях (сотни метров - км) ненадёжна — см. разбор в
// заметках проекта narodmon (audio-incident-recorder-design.md).
#pragma once
#include <stdint.h>
#include <stddef.h>

namespace Direction {

// BELOW  — звук пришёл в нижний (у устройства) микрофон раньше: источник
//          ближе к земле/горизонту установки (типично: бах в деревне рядом).
// ABOVE  — звук пришёл в верхний (на мачте) микрофон раньше: источник
//          приподнят над горизонтом установки (типично: гроза, что-то в
//          воздухе на удалении).
// CENTER — задержка в пределах "мёртвой зоны" — источник примерно на одной
//          высоте с линией микрофонов (см. DIRECTION_CENTER_DEADBAND_FRAC).
enum class Side : uint8_t { BELOW, CENTER, ABOVE, UNKNOWN };

struct Estimate {
    Side  side       = Side::UNKNOWN;
    float delayMs     = 0;   // оценённая задержка, мс. Знак: + значит звук
                              // пришёл в НИЖНИЙ канал РАНЬШЕ (источник ниже,
                              // BELOW), - значит раньше пришёл в ВЕРХНИЙ
                              // (источник выше, ABOVE).
    float confidence  = 0;   // 0..1, нормированный пик кросс-корреляции
                              // (низкая уверенность — тихое/смазанное событие
                              // или источник почти точно на той же высоте,
                              // что и линия микрофонов)
};

// Выделяет кольцевой буфер L/R в PSRAM. Не фатально при неудаче — просто
// направление не будет определяться, остальная детекция продолжит работать.
bool begin();

// Скармливать сюда КАЖДЫЙ кадр — сырые, не усреднённые каналы (вызывать из
// event_detector::detectorTask синхронно с моно-конвейером). Копит скользящее
// окно последних PREROLL_SAMPLES сэмплов (см. config.h).
void pushFrame(const int16_t *left, const int16_t *right, int n);

// Снимок направления по последнему DIRECTION_WINDOW_SEC-окну кольцевого
// буфера. Звать сразу в момент старта события (event_detector::startEvent()) —
// именно туда, в самую свежую часть буфера, попадает фронт атаки звука.
Estimate estimate();

const char *sideLabel(Side s);      // "снизу" / "сверху" / "по центру" / "?" — для CSV/Serial
const char *sideShortLabel(Side s); // "Н" / "В" / "Ц" / "?" — для тесной строки на экране

} // namespace Direction
